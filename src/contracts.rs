pub const SCHEMAS: [(&str, &str); 4] = [
    ("golden", "https://benchmark.slatedb.io/schema/golden.json"),
    ("result", "https://benchmark.slatedb.io/schema/result.json"),
    ("run", "https://benchmark.slatedb.io/schema/run.json"),
    ("series", "https://benchmark.slatedb.io/schema/series.json"),
];

pub fn generate(schema_directory: &Path, typescript_path: &Path, check: bool) -> Result<()> {
    let schemas = [
        ("golden", schema::<GoldenManifest>(SCHEMAS[0].1)?),
        ("result", schema::<WorkloadResult>(SCHEMAS[1].1)?),
        ("run", schema::<RunManifest>(SCHEMAS[2].1)?),
        ("series", schema::<WorkloadSeries>(SCHEMAS[3].1)?),
    ];
    for (name, schema) in schemas {
        write_or_check(
            &schema_directory.join(format!("{name}.json")),
            format!("{}\n", serde_json::to_string_pretty(&schema)?).as_bytes(),
            check,
        )?;
    }
    write_or_check(typescript_path, typescript().as_bytes(), check)
}

pub fn schema<T: JsonSchema>(id: &str) -> Result<Value> {
    let schema = SchemaGenerator::default().into_root_schema_for::<T>();
    let mut value = serde_json::to_value(schema)?;
    value
        .as_object_mut()
        .context("generated schema is not an object")?
        .insert("$id".to_string(), Value::String(id.to_string()));
    Ok(value)
}

fn typescript() -> String {
    let config = Config::default().with_large_int("number");
    let mut output = concat!(
        "// Generated by `slatedb-benchmark generate`; do not edit.\n\n",
        "export type JsonValue = null | boolean | number | string | ",
        "JsonValue[] | { [key: string]: JsonValue };\n\n"
    )
    .to_string();
    macro_rules! declaration {
        ($type:ty) => {{
            output.push_str("export ");
            output.push_str(&<$type as TS>::decl(&config));
            output.push_str("\n\n");
        }};
    }

    declaration!(Task);
    declaration!(DatasetConfig);
    declaration!(CacheConfig);
    declaration!(TaskConfig);
    declaration!(SourceIdentity);
    declaration!(Environment);
    declaration!(CheckpointReference);
    declaration!(GoldenDatasetMetadata);
    declaration!(ResultConfiguration);
    declaration!(GoldenManifest);
    declaration!(InitialState);
    declaration!(RateSummary);
    declaration!(ThroughputSummary);
    declaration!(LatencySummary);
    declaration!(DistributionSummary);
    declaration!(ApplicationMetrics);
    declaration!(ObjectStoreMetrics);
    declaration!(ProcessStatistics);
    declaration!(MachineStatistics);
    declaration!(SeriesReference);
    declaration!(HistogramSeries);
    declaration!(LatencyTimeSeries);
    declaration!(ApplicationSeries);
    declaration!(ObjectStoreSeries);
    declaration!(ProcessSeries);
    declaration!(MachineSeries);
    declaration!(WorkloadSeries);
    declaration!(WorkloadResult);
    declaration!(AppliedPatch);
    declaration!(TransferTool);
    declaration!(TransferLatencySummary);
    declaration!(TransferLatency);
    declaration!(TransferBenchmark);
    declaration!(TransferCapacity);
    declaration!(RunManifest);

    let workloads = Task::workloads()
        .map(|task| format!("  '{}'", task.as_str()))
        .collect::<Vec<_>>()
        .join(",\n");
    output.push_str("export const workloadNames = [\n");
    output.push_str(&workloads);
    output.push_str("\n] as const;\n");
    let schemas = SCHEMAS
        .iter()
        .map(|(name, _)| format!("  '{name}'"))
        .collect::<Vec<_>>()
        .join(",\n");
    output.push_str("\nexport const schemaNames = [\n");
    output.push_str(&schemas);
    output.push_str("\n] as const;\n");
    output
}

fn write_or_check(path: &Path, contents: &[u8], check: bool) -> Result<()> {
    if check {
        let existing = fs::read(path).with_context(|| format!("reading {}", path.display()))?;
        if existing != contents {
            bail!("{} is stale; run `cargo run -- generate`", path.display());
        }
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    }
    fs::write(path, contents).with_context(|| format!("writing {}", path.display()))
}

